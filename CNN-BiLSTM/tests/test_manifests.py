import csv

import pytest

from isl_slt.config import Data
from isl_slt.data.manifests import attach_interpreter, mapped_columns
from isl_slt.config import Adapter
from isl_slt.data.manifests import adapt_csv


def test_exact_duplicate_audit_and_conflicts(tmp_path):
    path = tmp_path / "annotations.csv"
    original = "uid,text\nsame-1, leading text\nsame-1, leading text\nother-1, leading text\n"
    path.write_text(original)
    adapter = Adapter(annotations=str(path), dataset_revision="synthetic", source_mapping=None)
    audit = {}
    records = adapt_csv(adapter, audit)
    assert len(records) == 2
    assert records[0].text == " leading text"
    assert audit["collapsed_exact_duplicates"][0]["dropped_row"] == 3
    assert path.read_text() == original
    path.write_text("uid,text\nsame-1, leading text\nsame-1,leading text\n")
    with pytest.raises(ValueError, match="Conflicting duplicate"):
        adapt_csv(adapter)


def test_real_gold_headers(tmp_path, record_factory):
    headers = ["uid", "Transcribed Text (text present in iSign/ISLTranslate translation dataset)",
               "Gold Translation (text generated by ISL Singer)"]
    path = tmp_path / "gold.csv"
    with path.open("w", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(headers)
        writer.writerows([(f"parent-{i}", f"transcript {i}", f"translation {i}") for i in range(3)])
    records = [record_factory(f"parent-{i}") for i in range(3)]
    attached = attach_interpreter(records, str(path), Data().interpreter_columns)
    assert [r.interpreter_text for r in attached] == [f"translation {i}" for i in range(3)]
    assert [r.interpreter_transcript for r in attached] == [f"transcript {i}" for i in range(3)]


def test_alias_ambiguity_still_fails():
    with pytest.raises(ValueError, match="exactly one"):
        mapped_columns(["short", "long"], {"text": ["short", "long"]})


def test_adapter_records_clip_type_without_claiming_source_verification(tmp_path):
    path = tmp_path / "types.csv"
    path.write_text("uid,text\nparent-1,sentence\n0EaLX2t1wPU_e1,definition\ncustom,unknown\n")
    records = adapt_csv(Adapter(annotations=str(path), dataset_revision="fixture", source_mapping=None))
    assert [r.clip_type for r in records] == ["sentence", "def", "unknown"]
    assert not any(r.source_verified for r in records)
